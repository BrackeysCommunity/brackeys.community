// seas measures water bodies and the crossings over them.
func seas(b *sheets.Book, g *gen.Gen, a *gen.Area, s *worldStats, inside func(gen.Hex) bool) {
	deep := int64(-1)
	for _, bb := range b.Biomes {
		if t := g.Terrain(bb.Terrain); !t.Passable && t.Wet() {
			deep = max(deep, bb.ElevationMax)
		}
	}
	water := func(i int) bool { return inside(a.Tiles[i].Hex) && a.Tiles[i].Elevation <= deep }
	points := map[int]bool{}
	for _, p := range a.Points {
		points[a.Index(p.Hex)] = true
	}
	seen := make([]bool, len(a.Tiles))
	for i, t := range a.Tiles {
		if !inside(t.Hex) {
			continue
		}
		if t.Yielded {
			s.yieldedAll++
		}
		if t.Ford {
			s.fords++
		}
		if !water(i) {
			continue
		}
		s.waterTiles++
		if seen[i] {
			continue
		}
		body := []int{i}
		seen[i] = true
		for k := 0; k < len(body); k++ {
			for _, n := range a.Neighbours(body[k]) {
				if !seen[n] && water(n) {
					seen[n] = true
					body = append(body, n)
				}
			}
		}
		in := map[int]bool{}
		lo, hi := [3]int64{1 << 40, 1 << 40, 1 << 40}, [3]int64{-1 << 40, -1 << 40, -1 << 40}
		for _, k := range body {
			in[k] = true
			h := a.Tiles[k].Hex
			for j, v := range [3]int64{h.Q, h.R, h.S()} {
				lo[j], hi[j] = min(lo[j], v), max(hi[j], v)
			}
		}
		if len(body) > s.biggestSea {
			s.biggestSea = len(body)
			s.biggestSpan = max(hi[0]-lo[0], hi[1]-lo[1], hi[2]-lo[2])
		}
		// A crossing is a run of yielded tiles; one that holds a pattern
		// point is that point's own way out, and is counted apart.
		cross := 0
		done := map[int]bool{}
		for _, k := range body {
			if !a.Tiles[k].Yielded || done[k] {
				continue
			}
			run := []int{k}
			done[k] = true
			point := false
			for j := 0; j < len(run); j++ {
				point = point || points[run[j]]
				for _, n := range a.Neighbours(run[j]) {
					if in[n] && a.Tiles[n].Yielded && !done[n] {
						done[n] = true
						run = append(run, n)
					}
				}
			}
			if point {
				s.pointRuns++
				continue
			}
			cross++
		}
		if len(body) >= spikeELakeMin {
			s.crossings = append(s.crossings, cross)
			if len(body) < spikeELakeMax {
				s.lakes++
				s.worstLake = max(s.worstLake, cross)
				if cross > spikeELakeCrossings {
					s.lakesOver2++
				}
			}
		}
	}
}

// fordRun is the longest stretch of wading: the widest span, in tiles,
// of any connected run of fords within the disc. Corridors that meet at
// one narrows make one run, so it is the length a walker wades, not a
// count of tiles.
func fordRun(a *gen.Area, inside func(gen.Hex) bool) int {
	seen := make([]bool, len(a.Tiles))
	best := 0
	for i, t := range a.Tiles {
		if !t.Ford || seen[i] || !inside(t.Hex) {
			continue
		}
		run := []int{i}
		seen[i] = true
		for k := 0; k < len(run); k++ {
			for _, n := range a.Neighbours(run[k]) {
				if !seen[n] && a.Tiles[n].Ford && inside(a.Tiles[n].Hex) {
					seen[n] = true
					run = append(run, n)
				}
			}
		}
		lo, hi := [3]int64{1 << 40, 1 << 40, 1 << 40}, [3]int64{-1 << 40, -1 << 40, -1 << 40}
		for _, k := range run {
			h := a.Tiles[k].Hex
			for j, v := range [3]int64{h.Q, h.R, h.S()} {
				lo[j], hi[j] = min(lo[j], v), max(hi[j], v)
			}
		}
		best = max(best, int(max(hi[0]-lo[0], hi[1]-lo[1], hi[2]-lo[2]))+1)
	}
	return best
}

// A lake is a body of water of at least spikeELakeMin and under
// spikeELakeMax tiles, crossed at most spikeELakeCrossings times.
const (
	spikeELakeMin       = 10
	spikeELakeMax       = 300
	spikeELakeCrossings = 2
)

// spikeEOpen is how many settlements are open in each tier measure.
var spikeEOpen = []int{1, 3, 10}

func opened(b *sheets.Book, g *gen.Gen, a *gen.Area, s *worldStats, inside func(gen.Hex) bool) {
	passable := func(i int) bool { return a.Passable(i) }
	for _, n := range spikeEOpen {
		m := map[int64]int{}
		for id, r := range a.Regions {
			if inside(r.Base.Centre) && g.Passable(r.Base.Terrain) {
				m[a.RegionTier(id, n)]++
			}
		}
		s.tiers[n] = m
		top := make([]bool, len(a.Tiles))
		for i, t := range a.Tiles {
			top[i] = passable(i) && g.TierAt(t.Hex, n) == 4
		}
		for k := range n {
			from := a.Index(g.Settlement(k).Hex)
			if from < 0 {
				continue
			}
			d := a.Walk([]int{from})
			best := int64(-1)
			for i := range d {
				if top[i] && d[i] >= 0 && (best < 0 || d[i] < best) {
					best = d[i]
				}
			}
			if best >= 0 {
				s.toTier4[n] = append(s.toTier4[n], best)
			}
		}
	}
}

func biomes(a *gen.Area, s *worldStats, inside func(gen.Hex) bool) {
	land := func(i int) bool { return inside(a.Tiles[i].Hex) && a.Passable(i) }
	seen := make([]bool, len(a.Tiles))
	var sizes, weighted []int
	for i, t := range a.Tiles {
		if !land(i) {
			continue
		}
		s.landTiles++
		if t.Secondary != "" {
			s.ecoTiles++
			x, y := t.Terrain, t.Secondary
			if y < x {
				x, y = y, x
			}
			s.pairs[x+" and "+y] = true
		}
		if t.Site == gen.SiteEdge {
			s.edgeSites++
		}
		if seen[i] {
			continue
		}
		patch := []int{i}
		seen[i] = true
		for k := 0; k < len(patch); k++ {
			for _, n := range a.Neighbours(patch[k]) {
				if !seen[n] && land(n) && a.Tiles[n].Terrain == t.Terrain {
					seen[n] = true
					patch = append(patch, n)
				}
			}
		}
		sizes = append(sizes, len(patch))
		for range patch {
			weighted = append(weighted, len(patch))
		}
	}
	slices.Sort(sizes)
	slices.Sort(weighted)
	s.patchMedian, s.patchTileMedian = q(sizes, 0.5), q(weighted, 0.5)
}

func countBelow(xs []int, v int) int {
	n, _ := slices.BinarySearch(xs, v)
	return n
}

func writePNG(path string, img image.Image) error {
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	if err := png.Encode(f, img); err != nil {
		_ = f.Close()
		return err
	}
	return f.Close()
}

const minutesPerDay = 24 * 60

func ticks(t int64) string {
	m := t * minutesPerDay / sheets.TicksPerDay
	if m < 60 {
		return fmt.Sprintf("%d ticks (%d min)", t, m)
	}
	return fmt.Sprintf("%d ticks (%.1f h)", t, float64(m)/60)
}
