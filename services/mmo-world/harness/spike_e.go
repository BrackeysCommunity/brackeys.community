func oneWorld(b *sheets.Book, seed int) (worldStats, error) {
	key := keys.Throwaway(fmt.Sprintf("spike-e-%d", seed)).Generation
	g, err := gen.New(b, key)
	if err != nil {
		return worldStats{}, err
	}
	s := worldStats{seed: seed, terrain: map[string]int{}, tiers: map[int]map[int64]int{}, toTier4: map[int][]int64{}, pairs: map[string]bool{}, novelty: map[int64][2]int{}, kinds: map[int64]map[string]int{}, rulesSeen: map[string]int{}}
	reach := int64(spikeEOut + spikeEMargin)

	// Generate every chunk of the disc in order, timed.
	cs := chunksIn(g, reach)
	start := time.Now()
	digests := make(map[gen.ChunkCoord]string, len(cs))
	for _, cc := range cs {
		g.Chunk(cc)
	}
	s.sweep, s.chunks = time.Since(start), len(cs)
	for _, cc := range cs {
		d, err := canon.Digest(g.Chunk(cc))
		if err != nil {
			return s, err
		}
		digests[cc] = d.String()
	}
	if err := chunkOrder(b, key, seed, g, cs, digests, &s); err != nil {
		return s, err
	}

	a := g.DiscArea(gen.Hex{}, reach)
	inside := func(h gen.Hex) bool { return h.Len() <= spikeEOut }

	// Reachability, and walks from the nearest settlement.
	var homes []int
	for _, i := range a.Settlements() {
		if inside(a.Tiles[i].Hex) {
			homes = append(homes, i)
		}
	}
	s.homes = len(homes)
	walk := a.Walk(homes[:1])
	nearest := a.Walk(homes)
	type lostPlace struct {
		h    gen.Hex
		what string
	}
	var lost []lostPlace
	for _, i := range homes {
		if walk[i] < 0 {
			lost = append(lost, lostPlace{a.Tiles[i].Hex, fmt.Sprintf("world %d: settlement at %v", seed, a.Tiles[i].Hex)})
		}
	}
	for _, pt := range a.Points {
		if !inside(pt.Hex) {
			continue
		}
		s.points++
		s.rulesSeen[pt.Rule]++
		i := a.Index(pt.Hex)
		if walk[i] < 0 {
			lost = append(lost, lostPlace{pt.Hex, fmt.Sprintf("world %d: %s %s at %v", seed, pt.Rule, pt.Place, pt.Hex)})
			continue
		}
		s.homeToPoint = append(s.homeToPoint, nearest[i])
		switch {
		case pt.Rule == "ring-of-eight":
			s.homeToRelay = append(s.homeToRelay, nearest[i])
		case pt.Rule == "triangle-of-pylons" && pt.Place == "vault":
			s.homeToVault = append(s.homeToVault, nearest[i])
		}
	}
	// A place the disc's walk misses may be joined by land beyond the
	// disc: walk a wider one before calling it unreachable.
	if len(lost) > 0 {
		wide := g.DiscArea(gen.Hex{}, spikeEWide)
		ww := wide.Walk([]int{wide.Index(a.Tiles[homes[0]].Hex)})
		for _, l := range lost {
			s.windowLost++
			if t := ww[wide.Index(l.h)]; t >= 0 {
				s.wideTicks = append(s.wideTicks, t)
				continue
			}
			s.unreachable++
			s.unreachableWhat = append(s.unreachableWhat, l.what)
		}
	}
	for _, t := range a.Tiles {
		if !inside(t.Hex) {
			continue
		}
		s.tiles++
		s.terrain[t.Terrain]++
		if t.Yielded {
			s.yielded++
		}
		if t.River {
			s.riverTiles++
		}
	}

	// Ring legs and settlement-to-settlement walks over a nearer disc.
	near := g.DiscArea(gen.Hex{}, spikeENear)
	var ring []int
	for _, pt := range near.Points {
		if pt.Rule == "ring-of-eight" {
			ring = append(ring, near.Index(pt.Hex))
		}
	}
	for k, i := range ring {
		if t := near.Walk([]int{i})[ring[(k+1)%len(ring)]]; t >= 0 {
			s.relayLeg = append(s.relayLeg, t)
		}
	}
	for n := range 6 {
		from := a.Index(g.Settlement(n).Hex)
		d := a.Walk([]int{from})
		best := int64(-1)
		for _, h := range homes {
			if h != from && d[h] >= 0 && (best < 0 || d[h] < best) {
				best = d[h]
			}
		}
		if best >= 0 {
			s.homeToHome = append(s.homeToHome, best)
		}
	}

	regionsAndNovelty(b, g, a, &s, inside)
	biomes(a, &s, inside)
	seas(b, g, a, &s, inside)
	s.fordRun = fordRun(a, inside)
	opened(b, g, a, &s, inside)

	if seed < spikeEPictures {
		s.pic = render.HexMap(g.DiscArea(gen.Hex{}, spikeEOut), 2)
		if seed < 4 {
			s.close = render.HexMap(g.DiscArea(gen.Hex{}, spikeENear-30), 8)
		}
	}
	return s, nil
}

// chunksIn lists the chunks that hold any tile within reach of the origin.
func chunksIn(g *gen.Gen, reach int64) []gen.ChunkCoord {
	var out []gen.ChunkCoord
	seen := map[gen.ChunkCoord]bool{}
	for _, h := range hex.Disc(reach) {
		if cc := g.ChunkOf(h); !seen[cc] {
			seen[cc] = true
			out = append(out, cc)
		}
	}
	return out
}

func chunkOrder(b *sheets.Book, key draw.Key, seed int, first *gen.Gen, cs []gen.ChunkCoord, want map[gen.ChunkCoord]string, s *worldStats) error {
	var inner []gen.ChunkCoord
	for _, cc := range cs {
		if first.ChunkCentre(cc).Len() <= spikeEOut {
			inner = append(inner, cc)
		}
	}
	d := draw.NewDrawer(keys.Throwaway("spike-e-order").Roll)
	order := d.Shuffle(len(inner), "order", draw.Int(int64(seed)))
	if seed >= spikeEOrderAll {
		order = order[:spikeEOrderPick]
	}
	g, err := gen.New(b, key)
	if err != nil {
		return err
	}
	check := func(g *gen.Gen, cc gen.ChunkCoord) error {
		dg, err := canon.Digest(g.Chunk(cc))
		if err != nil {
			return err
		}
		s.orderChecked++
		if dg.String() != want[cc] {
			s.orderMismatch++
		}
		return nil
	}
	for _, k := range order {
		if err := check(g, inner[k]); err != nil {
			return err
		}
	}
	for _, k := range order[:spikeEColdChunks] {
		fresh, err := gen.New(b, key)
		if err != nil {
			return err
		}
		if err := check(fresh, inner[k]); err != nil {
			return err
		}
	}
	return nil
}

// coldChunks times single chunks from fresh generators, one at a time on
// one core, at a spread of distances.
func coldChunks(b *sheets.Book) ([]time.Duration, error) {
	var out []time.Duration
	for seed := range spikeECold {
		key := keys.Throwaway(fmt.Sprintf("spike-e-%d", seed)).Generation
		for k := range spikeEColdChunks {
			g, err := gen.New(b, key)
			if err != nil {
				return nil, err
			}
			cc := g.ChunkOf(gen.Hex{Q: int64(k) * spikeEOut / spikeEColdChunks, R: -int64(seed % spikeEColdChunks)})
			start := time.Now()
			g.Chunk(cc)
			out = append(out, time.Since(start))
		}
	}
	return out, nil
}

func regionsAndNovelty(b *sheets.Book, g *gen.Gen, a *gen.Area, s *worldStats, inside func(gen.Hex) bool) {
	minT, maxT := sheets.IntParam(b.MapParams, "region-min-tiles"), sheets.IntParam(b.MapParams, "region-max-tiles")
	var land []int
	for id, r := range a.Regions {
		if g.Passable(r.Base.Terrain) && inside(r.Base.Centre) {
			land = append(land, id)
		}
	}
	slices.SortFunc(land, func(x, y int) int {
		rx, ry := a.Regions[x].Base, a.Regions[y].Base
		if rx.Distance != ry.Distance {
			return int(rx.Distance - ry.Distance)
		}
		if rx.ID.I != ry.ID.I {
			return int(rx.ID.I - ry.ID.I)
		}
		return int(rx.ID.J - ry.ID.J)
	})
	seen := map[string]bool{}
	pointsIn := map[int][]gen.PatternPoint{}
	for _, pt := range a.Points {
		r := a.TileRegion[a.Index(pt.Hex)]
		pointsIn[r] = append(pointsIn[r], pt)
	}
	for _, id := range land {
		r := a.Regions[id]
		s.regions++
		s.regionSizes = append(s.regionSizes, len(r.Tiles))
		if int64(len(r.Tiles)) >= minT && int64(len(r.Tiles)) <= maxT {
			s.inBand++
		}
		band := min(r.Base.Distance/spikeEBand, spikeEOut/spikeEBand-1)
		if s.kinds[band] == nil {
			s.kinds[band] = map[string]int{}
		}
		fresh := map[string]bool{}
		try := func(kind, id string) {
			if id != "" && !seen[id] {
				seen[id] = true
				fresh[kind] = true
			}
		}
		if r.Base.Far != nil {
			try("far", r.Base.Far.ID)
		}
		if r.Base.Variant != "" {
			try("creature", "creature:"+r.Base.Creature+":"+r.Base.Variant)
		}
		for _, t := range r.Tiles {
			if v := a.Tiles[t].Variant; v != "" {
				try("biome", "biome:"+v)
			}
		}
		if r.Base.EdgeMaterial != nil {
			try("edge-material", r.Base.EdgeMaterial.ID)
		}
		if r.Base.EdgeCreature != "" {
			try("edge-creature", "edge-creature:"+r.Base.EdgeCreature+":"+r.Base.Edge)
		}
		for _, pt := range pointsIn[id] {
			try("pattern", "pattern:"+pt.Rule+":"+pt.Instance)
		}
		v := s.novelty[band]
		v[0]++
		if len(fresh) > 0 {
			v[1]++
		}
		s.novelty[band] = v
		for k := range fresh {
			s.kinds[band][k]++
		}
	}
}

