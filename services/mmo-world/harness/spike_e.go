	p("| Pattern points within %d tiles | %s |", spikeEOut, comma(int64(points)))
	p("| Starting settlements within %d tiles | %s |", spikeEOut, comma(int64(homes)))
	slices.Sort(wideTicks)
	p("| Missed by a walk inside the %d-tile disc | %s, in %d worlds |", spikeEOut+spikeEMargin, comma(int64(windowLost)), windowWorlds)
	if len(wideTicks) > 0 {
		p("| Of those, reached walking a %d-tile disc (land beyond the first disc joins them) | %s; walk median %s, max %s |", spikeEWide, comma(int64(len(wideTicks))), ticks(q(wideTicks, 0.5)), ticks(wideTicks[len(wideTicks)-1]))
	}
	p("| Unreachable from the first settlement (target: 0) | **%d**, in %d worlds |", unreachable, badWorlds)
